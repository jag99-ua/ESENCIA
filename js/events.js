(() => {
  const root = new URL("../", document.currentScript.src);
  const node = (tag, className, text) => {
    const result = document.createElement(tag);
    if (className) result.className = className;
    if (text) result.textContent = text;
    return result;
  };
  const assetUrl = value => {
    if (typeof value !== "string" || !value.trim()) return "";
    try {
      const url = new URL(value, root);
      return ["http:", "https:", "file:"].includes(url.protocol) ? url.href : "";
    } catch { return ""; }
  };
  const date = value => {
    const result = node("time", "event-date", value.split("-").reverse().join("."));
    result.dateTime = value;
    return result;
  };
  const all = () => window.ESENCIA_EVENTS.filter(event => event.active).slice().sort((a, b) => a.date.localeCompare(b.date));
  const detailUrl = id => new URL("events/event.html?id=" + encodeURIComponent(id), root).href;
  const applyTheme = (target, event) => {
    target.style.removeProperty("--event-accent");
    target.style.removeProperty("--event-secondary");
    if (event?.accent && CSS.supports("color", event.accent)) target.style.setProperty("--event-accent", event.accent);
    if (event?.secondary && CSS.supports("color", event.secondary)) target.style.setProperty("--event-secondary", event.secondary);
  };
  const poster = event => {
    const source = assetUrl(event.poster);
    const desktop = assetUrl(event.posterDesktop);
    const mobile = assetUrl(event.posterMobile);
    if (!source && !desktop && !mobile) return null;
    const picture = node("picture", "event-poster");
    if (mobile) {
      const variant = node("source");
      variant.media = "(max-width: 600px)";
      variant.srcset = mobile;
      picture.append(variant);
    }
    const img = node("img");
    img.src = desktop || source || mobile;
    img.alt = "Cartel original de " + event.displayName;
    // Variantes del mismo artwork; el navegador elige según tamaño y densidad.
    if (Array.isArray(event.posterSrcset) && !desktop && !mobile) {
      img.srcset = event.posterSrcset.filter(item => assetUrl(item.src) && Number.isInteger(item.width) && item.width > 0).map(item => assetUrl(item.src) + " " + item.width + "w").join(", ");
      img.sizes = "(min-width: 500px) 448px, calc(100vw - 32px)";
    }
    if (event.posterWidth > 0 && event.posterHeight > 0) { img.width = event.posterWidth; img.height = event.posterHeight; }
    img.loading = "lazy"; img.decoding = "async";
    picture.append(img);
    return picture;
  };
  window.ESENCIA_EVENT_UTILS = { root, node, assetUrl, date, all, detailUrl, applyTheme, poster };
})();
